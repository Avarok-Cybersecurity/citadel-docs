#!/usr/bin/env python3
"""Generates cdoc-shape's Unicode tables from the Unicode Character Database.

Usage: scripts/gen-unicode-tables.py <ucd-dir> [--check-rustybuzz <rustybuzz/src/hb>]

<ucd-dir> holds UnicodeData.txt, Scripts.txt, CompositionExclusions.txt,
DerivedCoreProperties.txt and emoji-data.txt (from emoji/) of the version named in VERSION, from
https://www.unicode.org/Public/<VERSION>/ucd/. The data is under the Unicode License V3
(crates/cdoc-shape/LICENSE-UNICODE). Output: crates/cdoc-shape/src/unicode/*_table.rs.

What is generated:
- PROPS, all of Unicode: the general categories shaping distinguishes (marks, spaces, format),
  default ignorables, and each mark's combining class as HarfBuzz reorders it (Hebrew, Arabic,
  Syriac, Telugu, Thai, Lao and Tibetan classes remapped, three characters overridden).
- SCRIPTS, all of Unicode, folded to common/inherited/Latin/Greek/Cyrillic/other.
- DECOMPOSE/COMPOSE: canonical (de)compositions of every character a shaped run can hold
  (scripts common, inherited, unknown, Latin, Greek, Cyrillic); composition excludes
  CompositionExclusions.txt only, as HarfBuzz does.
- EXTENDED_PICTOGRAPHIC, all of Unicode.

--check-rustybuzz compares the tables with the oracle's own (rustybuzz's src/hb directory).
"""
import os
import re
import sys

VERSION = (16, 0, 0)
GC = {'Mn': 1, 'Mc': 2, 'Me': 3, 'Zs': 4, 'Cf': 5}
IGNORABLE = 8
HIDDEN = 16
SCRIPT = {'Common': 0, 'Unknown': 0, 'Inherited': 1, 'Latin': 2, 'Greek': 3, 'Cyrillic': 4}
OTHER_SCRIPT = 5
SHAPED = {'Common', 'Unknown', 'Inherited', 'Latin', 'Greek', 'Cyrillic'}
# Combining classes HarfBuzz reorders by instead of Unicode's (hb-unicode.cc), so marks of
# those scripts come out in the order fonts expect.
MODIFIED_CCC = {
    10: 22, 11: 15, 12: 16, 13: 17, 14: 23, 15: 18, 16: 19, 17: 20, 18: 21, 19: 14, 20: 24,
    21: 12, 22: 25, 23: 13, 24: 10, 25: 11, 26: 26,
    27: 28, 28: 29, 29: 30, 30: 31, 31: 32, 32: 33, 33: 27, 34: 34, 35: 35, 36: 36,
    84: 0, 91: 0, 103: 3, 107: 107, 118: 118, 122: 122, 129: 129, 130: 132, 132: 131,
}
MODIFIED_CCC_OF = {0x1A60: 254, 0x0FC6: 254, 0x0F39: 127}
# Default ignorables HarfBuzz does not hide (Hangul fillers, shorthand format controls, FVS4).
NOT_IGNORED = {0x115F, 0x1160, 0x3164, 0xFFA0, 0x1BCA0, 0x1BCA1, 0x1BCA2, 0x1BCA3, 0x180F}
HIDDEN_CHARS = {0x034F, 0x180B, 0x180C, 0x180D} | set(range(0xE0020, 0xE0080))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'crates', 'cdoc-shape', 'src', 'unicode')
PER_LINE = 8


def ranges_file(path, prop):
    out = {}
    for line in open(path, encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        cps, value = [x.strip() for x in line.split(';')[:2]]
        if prop is not None and value != prop:
            continue
        lo, _, hi = cps.partition('..')
        for cp in range(int(lo, 16), int(hi or lo, 16) + 1):
            out[cp] = value
    return out


def unicode_data(path):
    data = {}
    lines = [l.split(';') for l in open(path, encoding='utf-8')]
    i = 0
    while i < len(lines):
        f = lines[i]
        cp = int(f[0], 16)
        if f[1].endswith(', First>'):
            for c in range(cp, int(lines[i + 1][0], 16) + 1):
                data[c] = (f[2], int(f[3]), '')
            i += 2
            continue
        data[cp] = (f[2], int(f[3]), f[5])
        i += 1
    return data


def compress(values):
    """(start, end, value) for runs of equal non-zero values."""
    runs = []
    for cp in sorted(values):
        v = values[cp]
        if v == 0:
            continue
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == v:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, v])
    return runs


def hx(v):
    return f'0x{v:04X}' if v <= 0xFFFF else f'0x{v >> 16:X}_{v & 0xFFFF:04X}'


def emit(name, doc, ty, rows, fmt, per_line=PER_LINE):
    lines = [f'/// {doc}', '#[rustfmt::skip]', f'pub(super) const {name}: &[{ty}] = &[']
    for i in range(0, len(rows), per_line):
        lines.append('    ' + ' '.join(fmt(r) + ',' for r in rows[i:i + per_line]))
    lines.append('];')
    return lines


def header():
    v = '.'.join(map(str, VERSION))
    return [
        f'// Generated by scripts/gen-unicode-tables.py from the Unicode Character Database {v}.',
        '// Do not edit. Data: Copyright (c) Unicode, Inc., Unicode License V3 (LICENSE-UNICODE).',
        '',
    ]


def write(name, lines):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f'{name}: {len(lines)} lines')


def main():
    ucd = sys.argv[1]
    path = lambda f: os.path.join(ucd, f)
    first = open(path('Scripts.txt'), encoding='utf-8').readline()
    assert first.startswith('# Scripts-%d.%d.%d' % VERSION), first
    data = unicode_data(path('UnicodeData.txt'))
    scripts = ranges_file(path('Scripts.txt'), None)
    ignorable = set(ranges_file(path('DerivedCoreProperties.txt'), 'Default_Ignorable_Code_Point')) - NOT_IGNORED
    exclusions = {int(l.split('#')[0], 16) for l in open(path('CompositionExclusions.txt')) if l.split('#')[0].strip()}
    pict = set(ranges_file(path('emoji-data.txt'), 'Extended_Pictographic'))

    props = {}
    for cp in set(data) | ignorable:
        gc, ccc, _ = data.get(cp, ('Cn', 0, ''))
        kind = GC.get(gc, 0)
        ccc = MODIFIED_CCC_OF.get(cp, MODIFIED_CCC.get(ccc, ccc)) if 1 <= kind <= 3 else 0
        props[cp] = kind | (IGNORABLE if cp in ignorable else 0) | (HIDDEN if cp in HIDDEN_CHARS else 0) | (ccc << 8)
    write('props_table.rs', header() + emit(
        'PROPS', 'Character properties by range: low byte kind bits, high byte (modified) combining class.',
        '(u32, u32, u16)', compress(props), lambda r: f'({hx(r[0])}, {hx(r[1])}, 0x{r[2]:04X})'))

    write('script_table.rs', header() + emit(
        'SCRIPTS', 'Script by range: 1 inherited, 2 Latin, 3 Greek, 4 Cyrillic, 5 other; gaps are common.',
        '(u32, u32, u8)', compress({cp: SCRIPT.get(s, OTHER_SCRIPT) for cp, s in scripts.items()}),
        lambda r: f'({hx(r[0])}, {hx(r[1])}, {r[2]})'))

    write('pict_table.rs', header() + emit(
        'EXTENDED_PICTOGRAPHIC', '`Extended_Pictographic` ranges (`emoji-data.txt`): what a ZWJ joins.',
        '(u32, u32)', compress({cp: 1 for cp in pict}), lambda r: f'({hx(r[0])}, {hx(r[1])})'))

    decomp = []
    for cp, (_, _, dm) in sorted(data.items()):
        if dm and not dm.startswith('<') and scripts.get(cp, 'Unknown') in SHAPED:
            parts = [int(x, 16) for x in dm.split()]
            decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
    compose = sorted((i for i, (cp, a, b) in enumerate(decomp) if b and cp not in exclusions),
                     key=lambda i: (decomp[i][1], decomp[i][2]))
    lines = header() + emit(
        'DECOMPOSE', 'Canonical decompositions `(composed, first, second or 0)`, sorted by composed.',
        '(u32, u32, u32)', decomp, lambda r: f'({hx(r[0])}, {hx(r[1])}, {hx(r[2])})')
    lines += [''] + emit('COMPOSE', 'Indices into `DECOMPOSE` of the pairs that compose, sorted by pair.',
                         'u16', compose, str, per_line=24)
    write('norm_table.rs', lines)

    if '--check-rustybuzz' in sys.argv:
        hb = sys.argv[sys.argv.index('--check-rustybuzz') + 1]
        shaped = lambda cp: scripts.get(cp, 'Unknown') in SHAPED
        check_norm(os.path.join(hb, 'unicode_norm.rs'), decomp, compose, shaped)
        check_sets(os.path.join(hb, 'unicode.rs'), pict, ignorable)


def check_norm(path, decomp, compose, shaped):
    text = open(path, encoding='utf-8').read()
    theirs_d = {int(a, 16): (int(b, 16), int(c, 16) if c else 0)
                for a, b, c in re.findall(r"\('\\u\{(\w+)\}', '\\u\{(\w+)\}', (?:Some\('\\u\{(\w+)\}'\)|None)\)", text)
                if shaped(int(a, 16))}
    ours_d = {cp: (a, b) for cp, a, b in decomp}
    assert ours_d == theirs_d, sorted(set(ours_d.items()) ^ set(theirs_d.items()))[:10]
    theirs_c = {(int(k) >> 32, int(k) & 0xFFFFFFFF): int(ch, 16)
                for k, ch in re.findall(r"\((\d+), '\\u\{(\w+)\}'\)", text) if shaped(int(ch, 16))}
    ours_c = {(decomp[i][1], decomp[i][2]): decomp[i][0] for i in compose}
    assert ours_c == theirs_c, sorted(set(ours_c.items()) ^ set(theirs_c.items()))[:10]
    print(f'rustybuzz check OK: {len(ours_d)} decompositions, {len(ours_c)} compositions')


def match_set(text, fn):
    body = text[text.index(fn):]
    body = body[:body.index('\n    }\n')]
    return body


def check_sets(path, pict, ignorable):
    text = open(path, encoding='utf-8').read()
    body = match_set(text, 'fn is_emoji_extended_pictographic(self) -> bool {')
    theirs = set()
    for lo, hi in re.findall(r'0x([0-9A-F]+)(?:\.\.=0x([0-9A-F]+))? => true', body):
        theirs.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    assert pict == theirs, sorted(pict ^ theirs)[:20]
    body = match_set(text, 'fn is_default_ignorable(self) -> bool {')
    theirs = set()
    for m in re.finditer(r'\(0x([0-9A-F]+)\.\.=0x([0-9A-F]+)\)\.contains|ch == 0x([0-9A-F]+)', body):
        if m.group(3):
            theirs.add(int(m.group(3), 16))
        else:
            theirs.update(range(int(m.group(1), 16), int(m.group(2), 16) + 1))
    assert ignorable == theirs, sorted(ignorable ^ theirs)[:20]
    print(f'rustybuzz check OK: {len(pict)} Extended_Pictographic, {len(ignorable)} default ignorables')


if __name__ == '__main__':
    main()
