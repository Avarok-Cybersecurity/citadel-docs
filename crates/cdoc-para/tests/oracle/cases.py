"""Writes tests/golden/cases.rs: small paragraphs whose optimum is decided by TeX's tie-breaking
(`d <= minimal_demerits`, the later node wins) or by its fitness-class pruning
(`minimum_demerits + adj_demerits`), broken by TeX itself.

Each line of cases.txt is `width tolerance items`, items comma-separated: `b<w>` a box,
`h<w>` a word of width w with a discretionary hyphen (width 40) in its middle, `g<y>/<z>` glue
of width 100, stretch y, shrink z. Units are scaled points. Plain TeX's parameters, with
\\pretolerance=-1 and the case's \\tolerance.

usage: python3 -I cases.py   (needs tex on PATH)
"""
import os, re, shutil, subprocess, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))

def items_of(desc):
    items = []
    for tok in desc.split(','):
        kind, rest = tok[0], tok[1:]
        if kind == 'b':
            items.append(('box', int(rest)))
        elif kind == 'h':
            w = int(rest)
            items += [('box', w // 2), ('soft',), ('box', w - w // 2)]
        else:
            y, z = rest.split('/')
            items.append(('glue', int(y), int(z)))
    return items + [('pen', 10000), ('fil',), ('pen', -10000)]

def tex_breaks(desc, width, tolerance):
    items = items_of(desc)
    boxes = [k for k, it in enumerate(items) if it[0] == 'box']
    body = []
    for k, it in enumerate(items[:-3]):
        if it[0] == 'box':
            body.append('\\vrule width%dsp height0pt depth%dpt' % (it[1], boxes.index(k) + 1))
        elif it[0] == 'soft':
            body.append('\\discretionary{\\vrule width40sp height0pt depth999pt}{}{}')
        else:
            body.append('\\hskip100sp plus%dsp minus%dsp' % (it[1], it[2]))
    work = tempfile.mkdtemp()
    try:
        tex = ('\\showboxdepth=10 \\showboxbreadth=100000 \\parindent=0pt \\parfillskip=0pt plus1fil\n'
               '\\pretolerance=-1 \\tolerance=%d \\hbadness=10000 \\hfuzz=\\maxdimen\n'
               '\\setbox1\\vbox{\\hsize=%dsp \\noindent\n%s\\par}\\showbox1\n\\end\n'
               % (tolerance, width, '%\n'.join(body)))
        open(os.path.join(work, 'c.tex'), 'w').write(tex)
        subprocess.run(['tex', '-interaction=nonstopmode', 'c.tex'], cwd=work, capture_output=True)
        log = open(os.path.join(work, 'c.log')).read()
    finally:
        shutil.rmtree(work)
    lines = []
    for l in log.split('\n'):
        if re.match(r'^\.\\hbox', l):
            lines.append(None)
        m = re.match(r'^\.\.\\rule\(0\.0\+([\d.]+)\)', l)
        if m and int(float(m.group(1))) != 999:
            lines[-1] = int(float(m.group(1)))
    breaks = [boxes[last - 1] + 1 for last in lines[:-1]] + [len(items) - 1]
    return breaks

out = ['//! Generated by tests/oracle/cases.py from TeX 3.141592653 (TeX Live 2024). Do not edit.', '',
       '/// (line width, tolerance, items as in cases.py, TeX\'s break positions).',
       '#[rustfmt::skip]', 'pub const CASES: &[(i32, i32, &str, &[usize])] = &[']
for line in open(os.path.join(HERE, 'cases.txt')):
    if not line.strip() or line.startswith('#'):
        continue
    width, tol, desc = line.split()
    b = tex_breaks(desc, int(width), int(tol))
    out.append('    (%s, %s, "%s", &[%s]),' % (width, tol, desc, ', '.join(map(str, b))))
out.append('];')
open(os.path.join(HERE, '..', 'golden', 'cases.rs'), 'w').write('\n'.join(out) + '\n')
