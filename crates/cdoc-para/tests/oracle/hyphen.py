"""Writes tests/golden/hyphen.rs: every word of words-<tag>.txt as TeX hyphenates it with
patterns/hyph-<tag>.tex and the file's typesetting hyphen minimums (see hyphenate.py).

usage: python3 -I hyphen.py   (needs tex on PATH)
"""
import os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
LANGS = [('EN_US', 'en-us', 2, 3), ('EN_GB', 'en-gb', 2, 3), ('DE_1996', 'de-1996', 2, 2),
         ('FR', 'fr', 2, 2), ('ES', 'es', 2, 2)]
out = ['//! Generated by tests/oracle/hyphen.py from TeX 3.141592653 (TeX Live 2024). Do not edit.', '']
for const, tag, left, right in LANGS:
    tsv = subprocess.run([sys.executable, '-I', os.path.join(HERE, 'hyphenate.py'),
                          os.path.join(HERE, '..', '..', 'patterns', 'hyph-%s.tex' % tag),
                          str(left), str(right), os.path.join(HERE, 'words-%s.txt' % tag)],
                         capture_output=True, text=True, check=True).stdout
    pairs = [l.split('\t')[1] for l in tsv.strip().split('\n')]
    out.append('/// `hyph-%s.tex`, lefthyphenmin %d, righthyphenmin %d: words as TeX hyphenates them.' % (tag, left, right))
    out.append('#[rustfmt::skip]')
    out.append('pub const %s: &[&str] = &[' % const)
    for k in range(0, len(pairs), 5):
        out.append('    ' + ' '.join('"%s",' % p for p in pairs[k:k + 5]))
    out.append('];')
open(os.path.join(HERE, '..', 'golden', 'hyphen.rs'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
