//! The domain a `.docx` can hold, as a projection on generated documents.
//!
//! The model strategies generate any combination of values; a `.docx` has fewer degrees of
//! freedom. This maps a generated document to the nearest one the format represents, so the
//! round-trip property is "reading what was written gives the projection". Each rule names the
//! format fact it encodes.

use cdoc_docx::inherit_headers_and_footers;
use cdoc_model::{CommentId, Document, FontSize, Paragraph, Table};

/// Comment ranges open and close between runs: a continuing range keeps its place and a new
/// one is appended, so that is the only order a list of anchors can come back in.
fn anchor_order(p: &mut Paragraph) {
    let mut active: Vec<CommentId> = Vec::new();
    for inline in &mut p.inlines {
        let now = std::mem::take(&mut inline.marks.comments);
        active.retain(|id| now.contains(id));
        for id in now {
            if !active.contains(&id) {
                active.push(id);
            }
        }
        inline.marks.comments.clone_from(&active);
    }
}

/// Two adjacent tables in one container would read back as the same two tables; nothing to do.
/// Rows may be ragged but merged cells are generated by a dedicated strategy, so generated
/// documents carry no vertical merges.
fn no_vertical_merges(t: &mut Table) {
    for cell in t.rows.iter_mut().flat_map(|r| r.cells.iter_mut()) {
        cell.properties.row_span = 1;
    }
}

/// The projection.
pub fn canonical(mut doc: Document) -> Document {
    // Test default (PCND): the model requires document defaults to name a font and a size; the
    // reader fills a missing one from the built-in sheet and reports it, so generated documents
    // are given one up front.
    let run = &mut doc.styles.defaults.run;
    run.font.get_or_insert_with(|| "Calibri".to_owned());
    run.size.get_or_insert(FontSize(22));
    doc.for_each_paragraph_mut(&mut anchor_order);
    doc.for_each_table_mut(&mut no_vertical_merges);
    let _ = cdoc_docx::repair_references(&mut doc);
    // A reply names its parent by paragraph id in `commentsExtended`; a parent that is not a
    // comment, or is the comment itself, has no such paragraph.
    let ids: Vec<CommentId> = doc.comments.iter().map(|c| c.id.clone()).collect();
    for c in &mut doc.comments {
        if c.parent
            .as_ref()
            .is_some_and(|p| p == &c.id || !ids.contains(p))
        {
            c.parent = None;
        }
    }
    doc.normalize();
    inherit_headers_and_footers(&mut doc.sections);
    doc
}
