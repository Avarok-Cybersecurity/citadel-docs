pub(super) fn exact(what: &str) -> Option<Kind> {
    EXACT
        .iter()
        .chain(super::tiptap::EXACT)
        .find(|(w, ..)| *w == what)
        .map(|&(_, severity, label)| Kind::new(severity, label))
}

/// The pattern a sentence with a value in it matches; the value is a non-empty run without
/// spaces, so "an image" does not match `"" + " read as its text"` by accident.
pub(super) fn pattern(what: &str) -> Option<Kind> {
    PATTERNS
        .iter()
        .chain(super::tiptap::PATTERNS)
        .find(|(start, end, ..)| {
            what.strip_prefix(start)
                .and_then(|rest| rest.strip_suffix(end))
                .is_some_and(|value| !value.is_empty() && (end.is_empty() || !value.contains(' ')))
        })
        .map(|&(_, _, severity, label)| Kind::new(severity, label))
}
